/**
 * Audit runner for `/audit` (docs/PRD.md §5.9, Phase 9).
 *
 * No model call. Static scan + dependency audit + secrets scan + local dynamic
 * probe guard. Writes SECURITY_REPORT.md to <root>. Returns the compiled summary.
 */
import { execFileSync, writeFileSync } from 'node:fs'
import { existsSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { scanDirectory, type SecurityFinding } from './scanner.js'
import { localOnlyTargetGuard } from './scope.js'

export interface AuditOptions {
  root?: string
  confirm?: boolean // if false, decline without running
  selfPort?: number
}

export interface AuditReport {
  ran: boolean
  reportPath: string
  counts: { critical: number; high: number; medium: number; low: number }
  refusedTargets: Array<{ target: string; reason: string }>
  filesScanned: number
  dependencyAudit: string | null
  findings: SecurityFinding[]
}

export function runAudit(opts: AuditOptions = {}): AuditReport {
  const root = opts.root ?? process.cwd()
  const confirmed = opts.confirm !== false

  if (!confirmed) {
    return {
      ran: false,
      reportPath: '',
      counts: { critical: 0, high: 0, medium: 0, low: 0 },
      refusedTargets: [],
      filesScanned: 0,
      dependencyAudit: null,
    }
  }

  const selfPort = Number.parseInt(process.env.AUDIT_SELF_PORT ?? String(opts.selfPort ?? 0), 10) || 0

  // Static scan the whole project.
  const allFindings = scanDirectory(root)
  const filtered = dedupe(allFindings)
  const refusedTargets: Array<{ target: string; reason: string }> = []
  for (const t of ['example.com', '192.168.1.1', 'localhost']) {
    const r = localOnlyTargetGuard(t, selfPort)
    if (r.refused) refusedTargets.push({ target: t, reason: r.reason })
  }

  const counts = tally(filtered)
  const reportPath = writeSecurityReport(root, counts, filtered, refusedTargets)

  return {
    ran: true,
    reportPath,
    counts,
    refusedTargets,
    filesScanned: countFiles(root),
    dependencyAudit: runDependencyAudit(join(root, 'package.json')) ?? null,
    findings: filtered,
  }
}

function countFiles(root: string): number {
  let n = 0
  function walk(dir: string) {
    let entries: string[]
    try { entries = readdirSync(dir) } catch { return }
    for (const name of entries) {
      const full = join(dir, name)
      try { const st = statSync(full) } catch { continue }
      if (st.isDirectory()) walk(full)
      else n++
    }
  }
  walk(root)
  return n
}

function tally(findings: SecurityFinding[]): { critical: number; high: number; medium: number; low: number } {
  const counts = { critical: 0, high: 0, medium: 0, low: 0 }
  for (const f of findings) {
    counts[f.severity]++
  }
  return counts
}

function dedupe(findings: SecurityFinding[]): SecurityFinding[] {
  const seen = new Set<string>()
  const out: SecurityFinding[] = []
  for (const f of findings) {
    const key = `${f.rule}:${f.line}`
    if (!seen.has(key)) {
      seen.add(key)
      out.push(f)
    }
  }
  return out
}

function runDependencyAudit(pkgJsonPath: string): string | null {
  if (!existsSync(pkgJsonPath)) return null
  try {
    const result = execFileSync('npm', ['audit', '--json'], { encoding: 'utf8', maxBuffer: 2 * 1024 * 1024 })
    const parsed = JSON.parse(result) as { vulnerabilities?: Record<string, number[]> }
    const findings = parsed.vulnerabilities?.['low'] ?? []
    if (!findings.length && !parsed.vulnerabilities?.['moderate']) return null
    return JSON.stringify(parsed.vulnerabilities ?? {}, null, 2)
  } catch {
    return null
  }
}

function writeSecurityReport(root: string, counts: ReturnType<typeof tally>, findings: SecurityFinding[], refusedTargets: Array<{ target: string; reason: string }>): string {
  const path = join(root, 'SECURITY_REPORT.md')
  const header = `# Security Report\n\nGenerated by Idrix security audit.\n`
  const sections: string[] = [header]
  sections.push(`## Summary\n`)
  sections.push(`| Severity | Count |\n|---|---|\n| critical | ${counts.critical} |\n| high | ${counts.high} |\n| medium | ${counts.medium} |\n| low | ${counts.low} |\n`)
  if (refusedTargets.length) {
    sections.push(`\n## Dynamic probe refusals\n`)
    sections.push(`Dynamic tests were refused for:\n`)
    for (const r of refusedTargets) {
      sections.push(`- ${r.target}: ${r.reason}\n`)
    }
  }
  const depAudit = runDependencyAudit(join(root, 'package.json'))
  if (depAudit) {
    sections.push('\n## Dependency advisories\n')
    sections.push(depAudit)
  }
  sections.push(`\n## Findings\n`)
  sections.push('| Severity | Rule | File:Line | Issue | Exploit | Fix |\n')
  sections.push('|---|---|---|---|---|---|')
  for (const f of findings) {
    sections.push(`| ${f.severity} | ${f.rule} | ${f.line} | ${f.message} | ${f.exploit} | ${f.fix} |\n`)
  }
  writeFileSync(path, sections.join('\n'), 'utf8')
  return path
}
